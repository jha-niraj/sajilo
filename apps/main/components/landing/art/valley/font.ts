/** A lowercase glyph with no ascender: 2 empty rows, then its x-height rows (and descender rows, if any). */
function x(...rows: string[]): string[] {
    const w = rows[0]?.length ?? 4
    const blank = ".".repeat(w)
    return [blank, blank, ...rows]
}

