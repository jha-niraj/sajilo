/*
 * A crisp pixel font for the valley's speech bubbles and signs. Every glyph is 9 rows: 2 ascender rows, a 5-row
 * x-height, 2 descender rows. Capitals and digits are 7 rows tall (rows 0-6). Most glyphs are 4 wide; m, w, v and T are
 * 5; i, l, punctuation are narrower. Drawn as real pixels (an SVG path per colour), never a system font.
 */

