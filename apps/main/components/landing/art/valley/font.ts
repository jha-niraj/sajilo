function glyph(ch: string): readonly string[] {
    return GLYPHS[ch] ?? GLYPHS["?"] ?? []
}

function glyphWidth(ch: string): number {
    return glyph(ch).reduce((m, r) => Math.max(m, r.length), 0)
}

/** Width in pixels of `text` (1 pixel between letters). */
export function measure(text: string): number {
    return [...text].reduce((w, ch, i) => w + glyphWidth(ch) + (i > 0 ? 1 : 0), 0)
}

/** Draws `text` with its ascender line at `y`. Returns the width drawn. */
export function write(g: Grid, x: number, y: number, text: string, key: string): number {
    let cx = x
    ;[...text].forEach((ch, i) => {
        if (i > 0) cx += 1
        const rows = glyph(ch)
        rows.forEach((row, r) => {
            for (let c = 0; c < row.length; c++) if (row[c] === "#") g.set(cx + c, y + r, key)
        })
        cx += glyphWidth(ch)
    })
    return cx - x
}
